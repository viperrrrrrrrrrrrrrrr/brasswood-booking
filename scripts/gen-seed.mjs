// Generates SQL seed files from src/data/seed.ts (the same data the static demo uses).
//   node scripts/gen-seed.mjs --base   -> seed/seed.sql            (settings, services, staff, hours — committed)
//   node scripts/gen-seed.mjs --demo   -> .wrangler/seed-demo.sql  (fake clients, bookings, days off around TODAY — never auto-applied)
import { build } from 'esbuild'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { tmpdir } from 'node:os'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const mode = process.argv.includes('--demo') ? 'demo' : 'base'

const out = join(tmpdir(), `brasswood-seed-${process.pid}.mjs`)
await build({ entryPoints: [join(root, 'src/data/seed.ts')], bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'error' })
const { createSeed } = await import(pathToFileURL(out).href)
const db = createSeed()

const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const cents = (usd) => Math.round(usd * 100)
const lines = []

if (mode === 'base') {
  lines.push('-- Brasswood base data: shop settings, services, specialists and their weekly hours.')
  lines.push('-- Generated by `node scripts/gen-seed.mjs --base`. Safe to re-run: existing rows are kept (INSERT OR IGNORE).')
  lines.push('-- Contains NO clients and NO bookings.')
  const s = db.settings
  lines.push(`INSERT OR IGNORE INTO settings (id, name, tagline, address, phone, email, slot_step_min, min_notice_min, horizon_days, timezone) VALUES (1, ${[s.name, s.tagline, s.address, s.phone, s.email, s.slotStepMin, s.minNoticeMin, s.horizonDays, 'America/New_York'].map(q).join(', ')});`)
  db.services.forEach((x, i) => lines.push(`INSERT OR IGNORE INTO services (id, name, description, category, duration_min, price_cents, active, sort_order) VALUES (${[x.id, x.name, x.description, x.category, x.durationMin, cents(x.priceUsd), x.active ? 1 : 0, i + 1].map(q).join(', ')});`))
  db.staff.forEach((m, i) => {
    lines.push(`INSERT OR IGNORE INTO staff (id, name, role, bio, color, active, sort_order) VALUES (${[m.id, m.name, m.role, m.bio, m.color, m.active ? 1 : 0, i + 1].map(q).join(', ')});`)
    for (const sid of m.serviceIds) lines.push(`INSERT OR IGNORE INTO staff_services (staff_id, service_id) VALUES (${q(m.id)}, ${q(sid)});`)
    m.hours.forEach((h, wd) => {
      if (h) lines.push(`INSERT OR IGNORE INTO staff_hours (staff_id, weekday, start_min, end_min, break_start_min, break_end_min) VALUES (${[m.id, wd, h.start, h.end, h.breakStart ?? null, h.breakEnd ?? null].map(q).join(', ')});`)
    })
  })
  writeFileSync(join(root, 'seed/seed.sql'), lines.join('\n') + '\n')
  console.log('wrote seed/seed.sql')
} else {
  lines.push('-- DEMO ONLY: fake clients (@example.com) and bookings around the day this file was generated.')
  lines.push('-- Never apply this to a database with real customers.')
  for (const o of db.timeOff) lines.push(`INSERT OR IGNORE INTO time_off (id, staff_id, date, note) VALUES (${[o.id, o.staffId, o.date, o.note].map(q).join(', ')});`)
  for (const c of db.clients) lines.push(`INSERT OR IGNORE INTO clients (id, name, phone, phone_digits, email, notes, created_at) VALUES (${[c.id, c.name, c.phone, c.phone.replace(/\D/g, ''), c.email.toLowerCase(), c.notes, c.createdAt].map(q).join(', ')});`)
  for (const b of db.bookings) lines.push(`INSERT OR IGNORE INTO bookings (id, code, service_id, staff_id, client_id, date, start_min, end_min, status, price_cents, notes, source, created_at) VALUES (${[b.id, b.code, b.serviceId, b.staffId, b.clientId, b.date, b.start, b.end, b.status, cents(b.priceUsd), b.notes, b.source, b.createdAt].map(q).join(', ')});`)
  mkdirSync(join(root, '.wrangler'), { recursive: true })
  writeFileSync(join(root, '.wrangler/seed-demo.sql'), lines.join('\n') + '\n')
  console.log(`wrote .wrangler/seed-demo.sql (${db.clients.length} clients, ${db.bookings.length} bookings)`)
}
